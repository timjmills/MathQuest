// Which + − × ÷ skills draw a kit answer slot the answer-box option can restyle?  (Wave 1 lane B)
//
//   node tests/scripts/ws-ansbox-measure.cjs           # measure and write js/modules/skill-ansbox-skills.js
//   node tests/scripts/ws-ansbox-measure.cjs --check   # measure, exit 1 if the written file is stale
//
// Owner ruling 2026-10-02: the answer-box style (`ansBox`: one box per digit / one box / off) is a
// teacher option on addition, subtraction, multiplication and division. A control that changes
// nothing is a lie on the teacher's screen (offeredOptionsFor), so the option is OFFERED only on
// the skills whose items are drawn by the kit's `stack`, `fact` or `equation` templates. This
// script generates 24 seeded items per skill (generateQuestionFor) and records the templates seen.
const fs = require('fs');
const path = require('path');
const { open, listSkills, ROOT } = require('../lib/ws-harness.cjs');

const OUT = path.join(ROOT, 'js/modules/skill-ansbox-skills.js');
const CATS = ['addition', 'subtraction', 'multiplication', 'division'];

(async () => {
    const app = await open({ seed: 1, viewport: { width: 1280, height: 900, deviceScaleFactor: 1 } });
    const { page } = app;
    const skills = (await listSkills(page)).filter((s) => CATS.includes(s.categoryId) && !/retired|tombstone/i.test(s.label || ''));
    const found = await page.evaluate(async (list) => {
        const { cellKindFor } = await import('/js/modules/screen-cell.js');
        const out = {};
        for (const { categoryId: c, skillId: k } of list) {
            const seen = new Set();
            for (let i = 0; i < 24; i++) {
                let q = null;
                try { q = window.generateQuestionFor({ category: c, skill: k, seed: 7001 + i, itemIndex: i, itemCount: 24 }); } catch (e) { q = null; }
                const t = q && q.cell && q.cell.template;
                if (t === 'stack' || t === 'fact' || t === 'equation') { seen.add(t); continue; }
                // a legacy-printed + − × ÷ item whose answer is one number in a column, a fact or an
                // equation: the legacy print slots (print-generate.js) and the screen kinds honour it too
                let k2 = null; try { k2 = q ? cellKindFor(q) : null; } catch (e) { k2 = null; }
                if (k2 && (k2.kind === 'stack' || k2.kind === 'fact' || k2.kind === 'eq')) seen.add(`legacy-${k2.kind}`);
            }
            if (seen.size) out[`${c}:${k}`] = [...seen].sort().join('+');
        }
        return out;
    }, skills);
    await app.close();
    const keys = Object.keys(found).sort();
    const body = `// GENERATED by tests/scripts/ws-ansbox-measure.cjs — do not edit by hand. Re-run the script.\n//\n`
        + `// The + − × ÷ skills whose items (24 seeded each) are a column, a fact or an equation with one\n`
        + `// numeric answer - kit templates, or legacy print with a screen stack / fact / equation - so the\n`
        + `// answer-box option (\`ansBox\`, owner ruling 2026-10-02) changes what they draw. Word problems,\n`
        + `// charts and models are not listed: their answer places are the drawing's own.\n`
        + `// skill-options.js offers the option on these skills only. ${keys.length} skills.\n`
        + `import { registerAnsBoxSkills } from './skill-options.js';\n\n`
        + `export const ANSBOX_SKILLS = Object.freeze({\n${keys.map((k) => `    '${k}': '${found[k]}',`).join('\n')}\n});\nregisterAnsBoxSkills(ANSBOX_SKILLS);\n`;
    if (process.argv.includes('--check')) {
        const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
        if (cur !== body) { console.log('ws-ansbox-measure: FAIL (js/modules/skill-ansbox-skills.js is stale; re-run without --check)'); process.exit(1); }
        console.log(`ws-ansbox-measure: OK (${keys.length} skills)`);
        return;
    }
    fs.writeFileSync(OUT, body);
    console.log(`ws-ansbox-measure: wrote ${keys.length} skills to js/modules/skill-ansbox-skills.js`);
})().catch((e) => { console.error(e); process.exit(1); });
