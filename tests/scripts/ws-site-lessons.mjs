// ws-site-lessons.mjs — generate js/modules/site-lessons-db.js, the compact copy of the school site's own lessons
// the White Rose lessons screen lists beside the White Rose steps (owner request 2026-10-17: "every lesson on
// the school site must be visible with its skills").
//
//   node tests/scripts/ws-site-lessons.mjs            write the db
//   node tests/scripts/ws-site-lessons.mjs --check    exit 1 when the committed db is stale
//
// Sources (both written by tests/scripts/ws-wrm-extract.cjs from the school curriculum site; never edit them here):
//   data/curriculum/site-lessons.json   every non-White-Rose lesson (CCSS "committee" BUILD lessons, Support lessons
//                                       that match no step, end-of-year lessons) and the assessments (domain exams,
//                                       MAP Growth windows), each with its stable site id "<grade>|-|<title slug>"
//   data/curriculum/wrm-steps.json      the step fields the screen composes sentences from: site.supportIn,
//                                       site.taughtIn (copied in / reviewed in a later grade) and enrichment
// Grades are written as the White Rose screen's grade ids (K, 1 … 5); the site id is kept as it is.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const rd = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));
const G = (g) => String(g || '').replace(/^G(?=\d)/, '');            // 'G4' -> '4', 'K' -> 'K', 'PK' -> 'PK'
const W = (w) => (/^W\d{2}$/.test(String(w || '')) ? w : null);
const STRAND = { standard: 'S', priority: 'P', intervention: 'I' };

const site = rd('data/curriculum/site-lessons.json');
const lessons = (site.lessons || []).map((l) => {
    const strands = 'SPI'.split('').filter((c) => (l.tracks || []).some((t) => STRAND[t] === c)).join('');
    return [l.id, G(l.grade), l.title, l.flag || '', l.supplement ? 1 : 0, l.ccss || [], l.ee || [], l.power ? 1 : 0, l.domain || '',
        l.block || null, W(l.firstWeek), (l.weeks || []).filter(W), strands, /domain tests?/i.test(l.unit || '') ? 1 : 0];
});
const assessments = (site.assessments || []).map((a) => [a.id, G(a.grade), a.title, a.kind || 'exam', a.domain || '', (a.weeks || []).filter(W)]);

const steps = rd('data/curriculum/wrm-steps.json');
const stepSite = {};
for (const y of steps.years || []) {
    for (const b of y.blocks || []) {
        for (const s of b.steps || []) {
            const site2 = s.site || {};
            const rec = {};
            if ((site2.supportIn || []).length) rec.s = site2.supportIn.map(G);
            if ((site2.taughtIn || []).length) rec.t = site2.taughtIn.map((x) => [G(x.grade), x.how || '', W(x.firstWeek)]);
            if (s.enrichment) rec.e = String(s.enrichment);
            if (Object.keys(rec).length) stepSite[s.id] = rec;
        }
    }
}

const out = `// GENERATED by tests/scripts/ws-site-lessons.mjs from data/curriculum/site-lessons.json and
// data/curriculum/wrm-steps.json — never hand-edit; regenerate after a site re-extract.
// SITE_LESSONS tuple: [siteId, grade, title, flag, supplement, ccss[], ee[], power, domain, block|null, firstWeek|null,
//   weeks[], strands (S/P/I), forDomainTest]
// SITE_ASSESSMENTS tuple: [siteId, grade, title, kind (exam|map), domain, weeks[]]
// STEP_SITE: stepId -> { s: grades that list the step as a Support lesson, t: [[grade, how, firstWeek]], e: enrichment }
export const SITE_LESSONS = ${JSON.stringify(lessons)};
export const SITE_ASSESSMENTS = ${JSON.stringify(assessments)};
export const STEP_SITE = ${JSON.stringify(stepSite)};
`;
const dbUrl = new URL('js/modules/site-lessons-db.js', root);
const msg = `${lessons.length} site lessons, ${assessments.length} assessments, ${Object.keys(stepSite).length} steps with site fields`;
if (process.argv.includes('--check')) {
    const cur = existsSync(dbUrl) ? readFileSync(dbUrl, 'utf8') : '';
    const okk = cur === out;
    console.log(`ws-site-lessons: ${okk ? 'OK' : 'FAIL (stale: run node tests/scripts/ws-site-lessons.mjs)'} — ${msg}`);
    process.exit(okk ? 0 : 1);
}
writeFileSync(dbUrl, out);
console.log(`ws-site-lessons: wrote js/modules/site-lessons-db.js — ${msg}`);
