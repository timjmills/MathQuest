#!/usr/bin/env node
// ws-wrm-bookmarks.mjs — the White Rose lesson bookmarks (critic 2026-10-30 W1, class LINK-DRIFT).
//
// A lesson link is #wrm/<grade>/<unit>/<slug> (wrm-links.js lessonHash). Until 2026-10-30 a White Rose row's link was
// its list NUMBER, and the school-site reorder of 2026-10-17 (commit 85b40359) moved every number: #wrm/3/D1/16 was
// "Patterns on the multiplication table" and became "Divide by 10". This script keeps that from happening again:
//
//   --freeze   (once; already done) the numbering before the reorder, read from git (85b40359^), as the frozen
//              table data/curriculum/wrm-legacy-hashes.json: old number -> [old title, the lesson's slug link today]
//              (only the numbers whose lesson moved or left the list); then --write-db.
//   --write-db js/modules/wrm-legacy-hashes-db.js from the JSON (the browser reads it; never hand-edit).
//   --pin      add the current links of every lesson to tests/fixtures/wrm-bookmarks.json as a NEW version
//              ({hash -> title}); an existing version is never rewritten. Run it at each deploy that changes the list.
//   --check    (default) the db matches the JSON, and EVERY pinned link of EVERY version still opens a lesson of the
//              title it was pinned with (a link made after the reorder may open the lesson it was made for before,
//              with the notice naming the pinned one). ws-wrm-page-unit.mjs runs this check.
//
// A renamed or re-slugged lesson fails --check; fix it with an alias in the JSON's "aliases" ({"<grade>/<old slug>":
// "<grade>/<unit>/<new slug>"}), never by re-pinning.

import { readFileSync, writeFileSync, existsSync, mkdtempSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const ROOT = new URL('../../', import.meta.url);
const JSON_PATH = new URL('data/curriculum/wrm-legacy-hashes.json', ROOT);
const DB_PATH = new URL('js/modules/wrm-legacy-hashes-db.js', ROOT);
const PIN_PATH = new URL('tests/fixtures/wrm-bookmarks.json', ROOT);
const REORDER = '85b40359';
const ts = (t) => String(t || '').toLowerCase().replace(/[^a-z0-9]+/g, '');

function dbText(j) {
    return `// wrm-legacy-hashes-db.js — GENERATED by \`node tests/scripts/ws-wrm-bookmarks.mjs --write-db\` from
// data/curriculum/wrm-legacy-hashes.json. Never hand-edit.
// LEGACY_HASHES: a numbered lesson link from before the ${j.renumbered} reorder -> [the title it opened, its link today ('' = no longer listed)].
// SLUG_ALIASES: '<grade>/<old slug>' -> '<grade>/<unit>/<slug>' for a lesson whose title (and so its link) changed.
export const LEGACY_DATE = ${JSON.stringify(j.renumbered)};
export const LEGACY_HASHES = ${JSON.stringify(j.hashes)};
export const SLUG_ALIASES = ${JSON.stringify(j.aliases || {})};
`;
}
const pathOf = (h) => h.replace(/^#wrm\//, '');

async function freeze() {
    const dir = mkdtempSync(join(tmpdir(), 'wrm-old-'));
    const f = join(dir, 'old-seq.mjs');
    writeFileSync(f, execFileSync('git', ['show', `${REORDER}^:js/modules/wrm-sequence-db.js`], { cwd: ROOT.pathname, maxBuffer: 1 << 26 }));
    const { WRM_SEQUENCE: OLD } = await import(f);
    const L = await import('../../js/modules/wrm-links.js');
    const all = L.allLessons();
    const hashes = {};
    const old = [];
    for (const g of OLD) for (const u of g.units) u.lessons.forEach((t, i) => {
        const key = `${g.id}:${u.id}:${i + 1}`;
        const now = L.lessonByKey(key);
        const hits = all.filter((l) => l.grade === g.id && (ts(l.rawTitle || l.title) === ts(t[0]) || ts(l.title) === ts(t[0])));
        const best = hits.find((l) => l === now) || hits.find((l) => l.unit === u.id) || hits[0] || null;
        old.push([`#wrm/${g.id}/${u.id}/${i + 1}`, String(t[0])]);
        if (best && best === now) return;   // the number meant this lesson then and now
        hashes[`${g.id}/${u.id}/${i + 1}`] = [String(t[0]), best ? pathOf(L.lessonHash(best)) : ''];
    });
    const j = { meta: { what: 'White Rose lesson links by number from before the school-site reorder, and where each lesson is now', source: `git ${REORDER}^ js/modules/wrm-sequence-db.js`, made: '2026-10-30' },
        renumbered: '2026-10-17', hashes, aliases: {} };
    writeFileSync(JSON_PATH, `${JSON.stringify(j, null, 1)}\n`);
    console.log(`froze ${Object.keys(hashes).length} moved or dropped numbers of ${old.length} (${Object.values(hashes).filter((x) => !x[1]).length} no longer listed)`);
    // the numbered links of the first deployed version, pinned with the title they opened then
    const pins = existsSync(PIN_PATH) ? JSON.parse(readFileSync(PIN_PATH, 'utf8')) : { versions: {} };
    const v = '2026-10-10 numbered (before the reorder)';
    if (!pins.versions[v]) { pins.versions[v] = Object.fromEntries(old); writeFileSync(PIN_PATH, `${JSON.stringify(pins, null, 1)}\n`); }
}

async function pin(name) {
    const L = await import('../../js/modules/wrm-links.js');
    const pins = existsSync(PIN_PATH) ? JSON.parse(readFileSync(PIN_PATH, 'utf8')) : { versions: {} };
    if (pins.versions[name]) { console.log(`version "${name}" is already pinned; pins are never rewritten`); return; }
    const all = L.allLessons();
    const after = '2026-10-17 numbered (after the reorder)';
    // the numbered links the page wrote from 2026-10-17 to 2026-10-30 (a row the site does not name)
    if (!pins.versions[after]) pins.versions[after] = Object.fromEntries(all.filter((l) => l.seq && !l.site).map((l) => [`#wrm/${l.grade}/${l.unit}/${l.n}`, l.title]));
    pins.versions[name] = Object.fromEntries(all.map((l) => [L.lessonHash(l), l.title]));
    writeFileSync(PIN_PATH, `${JSON.stringify(pins, null, 1)}\n`);
    console.log(`pinned ${all.length} links as "${name}"`);
}

/** Every pinned link resolves to its pinned title. Returns { checked, bad: [msg] }. */
export async function checkBookmarks() {
    const L = await import('../../js/modules/wrm-links.js');
    const bad = [];
    const j = JSON.parse(readFileSync(JSON_PATH, 'utf8'));
    if (readFileSync(DB_PATH, 'utf8') !== dbText(j)) bad.push('js/modules/wrm-legacy-hashes-db.js is stale (fix: node tests/scripts/ws-wrm-bookmarks.mjs --write-db)');
    const pins = existsSync(PIN_PATH) ? JSON.parse(readFileSync(PIN_PATH, 'utf8')) : { versions: {} };
    let checked = 0;
    for (const [ver, map] of Object.entries(pins.versions)) {
        for (const [hash, title] of Object.entries(map)) {
            checked += 1;
            const r = L.resolveLessonHash(hash);
            const got = r.lesson ? r.lesson.title : '';
            if (r.lesson && ts(got) === ts(title)) {
                if (r.legacy && !r.legacy.title) bad.push(`${ver} ${hash}: redirected with no notice title`);
                continue;
            }
            // a link to a lesson the school no longer lists: the notice names it
            if (!r.lesson && r.legacy && r.legacy.gone && ts(r.legacy.title) === ts(title)) continue;
            // a numbered link made after the reorder: the notice offers the lesson it was made for
            if (r.legacy && r.legacy.alt && ts(r.legacy.alt.title) === ts(title)) continue;
            bad.push(`${ver} ${hash}: pinned "${title}", opens "${got || '(nothing)'}"${r.legacy ? ' (redirected)' : ''}`);
        }
    }
    // every lesson's link today opens it, and no two lessons share one
    const seen = new Map();
    for (const l of L.allLessons()) {
        const h = L.lessonHash(l);
        if (/\/\d+$/.test(h)) bad.push(`${l.key}: link ${h} is a number`);
        if (seen.has(h)) bad.push(`${h}: ${seen.get(h)} and ${l.key} share a link`);
        seen.set(h, l.key);
        if (L.resolveLessonHash(h).lesson !== l) bad.push(`${l.key}: ${h} does not reopen it`);
    }
    return { checked, bad, versions: Object.keys(pins.versions).length };
}

const arg = process.argv[2] || '--check';
if (import.meta.url === `file://${process.argv[1]}`) {
    if (arg === '--freeze') { await freeze(); writeFileSync(DB_PATH, dbText(JSON.parse(readFileSync(JSON_PATH, 'utf8')))); }
    else if (arg === '--write-db') writeFileSync(DB_PATH, dbText(JSON.parse(readFileSync(JSON_PATH, 'utf8'))));
    else if (arg === '--pin') await pin(process.argv[3] || new Date().toISOString().slice(0, 10));
    else {
        const r = await checkBookmarks();
        for (const b of r.bad.slice(0, 20)) console.log('LINK-DRIFT', b);
        console.log(`ws-wrm-bookmarks: ${r.bad.length ? 'FAIL' : 'OK'} (${r.checked} pinned links in ${r.versions} versions, ${r.bad.length} bad)`);
        process.exit(r.bad.length ? 1 : 0);
    }
}
