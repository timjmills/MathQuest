// ws-mix-review-templates — the DRAWN template of every mixed-review pool skill (lead ruling 2026-11-20, "footprint kinds").
// One browser pass: each pool row's generator is run through generateQuestionFor on 6 fixed seeds, and the cell template
// it emits (print-sheet.js drawnTemplateOf: kitCellSpec, then a number family, as hostItem resolves it; else 'legacy') is recorded. The most frequent template wins (ties: the
// first seen). It writes the GENERATED module js/modules/mixed-review-templates.js, which mixed-review-pool.js reads to
// class a row (TEMPLATE_KIND -> KIND_CLASS in js/modules/mixed-review.js); the frozen V1 table is then re-pinned with
// `node tests/scripts/ws-mix-review.mjs --pin`.
//   node tests/scripts/ws-mix-review-templates.cjs            # regenerate the module
//   node tests/scripts/ws-mix-review-templates.cjs --check    # FAIL when the module differs from a fresh pass
const fs = require('fs');
const path = require('path');
const { open, ROOT } = require('../lib/ws-harness.cjs');

const OUT = path.join(ROOT, 'js/modules/mixed-review-templates.js');
const SEEDS = [11, 23, 37, 51, 67, 83];

(async () => {
  const app = await open({ seed: 1 });
  let map;
  try {
    map = await app.page.evaluate(async (seeds) => {
      const P = await import('/js/modules/mixed-review-pool.js');
      const PS = await import('/js/modules/print-sheet.js');
      const out = {};
      for (const r of P.poolRows()) {
        const [category, skill] = r.id.split(':');
        const seen = new Map();
        for (const seed of seeds) {
          let t = 'legacy';
          try { const q = window.generateQuestionFor({ category, skill, seed }); t = PS.drawnTemplateOf(q); } catch (e) { t = 'legacy'; }
          seen.set(t, (seen.get(t) || 0) + 1);
        }
        out[r.id] = [...seen.entries()].sort((a, b) => b[1] - a[1])[0][0];
      }
      return out;
    }, SEEDS);
  } finally { await app.close(); }
  const ids = Object.keys(map).sort();
  const body = `// GENERATED by node tests/scripts/ws-mix-review-templates.cjs (lead ruling 2026-11-20): the cell template each mixed-review
// pool skill's generator DRAWS (drawnTemplateOf over ${SEEDS.length} fixed seeds, the most frequent; 'legacy' = no kit cell).
// mixed-review-pool.js classes a row from this through TEMPLATE_KIND (js/modules/mixed-review.js). Never hand-edit.
export const DRAWN_TEMPLATES = Object.freeze({
${ids.map((id) => `    ${JSON.stringify(id)}: ${JSON.stringify(map[id])},`).join('\n')}
});
`;
  const counts = {}; for (const id of ids) counts[map[id]] = (counts[map[id]] || 0) + 1;
  if (process.argv.includes('--check')) {
    const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (old !== body) { console.log('ws-mix-review-templates: FAIL (js/modules/mixed-review-templates.js differs from a fresh pass; regenerate it)'); process.exit(1); }
    console.log(`ws-mix-review-templates: OK (${ids.length} skills)`); return;
  }
  fs.writeFileSync(OUT, body);
  console.log(`ws-mix-review-templates: OK (${ids.length} skills; ${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([t, n]) => `${t} ${n}`).join(', ')})`);
})().catch((e) => { console.log(`ws-mix-review-templates: FAIL (${e.message})`); process.exit(1); });
