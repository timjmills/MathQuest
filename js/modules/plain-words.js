// plain-words.js — the ONE definition of a teacher-facing plain-English line (lead decision, fix round 6:
// a WHITELIST, not a blacklist). Every line on White Rose lessons, Skills to be made and the MAP task notes
// is either COMPOSED from structured fields (skill labels, step titles, grades, week numbers, option labels,
// entry names) or is a build-team note that passes isPlain() WHOLE. A note that fails is never shown and
// never partly rewritten: the composed sentence stands alone. The gates (tests/lib/wrm-jargon.cjs) import
// this same check, so the screens and the gate cannot drift.
//
// A line is plain when:
//   - every word token is in PLAIN_WORDS (plain-words-db.js, generated by tests/scripts/ws-plain-words.mjs
//     from our own teacher-facing strings, skill labels, White Rose step titles, the standards' wording,
//     the Teaching Guides' key vocabulary and the hand list data/curriculum/plain-words-hand.txt), and not in
//     DENY; or is a number ("12", "1,000", "2s", "3rd"), a standard code ("3.NF.A.1"), an allowed acronym
//     (ACRONYMS) or one of the single letters a, I, x;
//   - no token mixes case inside it (camelCase, "DesCartes") unless it is an allowed acronym;
//   - brackets and quotes balance, it starts with a capital, a digit or a quote (no fragment), no word is
//     doubled ("the the"), and no code characters ( _ { } [ ] ` | < > \ ) appear.
//
// Pure: no window, no DOM, no state.

import { PLAIN_WORDS } from './plain-words-db.js';

const WORDS = new Set(PLAIN_WORDS.split(' '));
/** Build words that never pass, even when a source happens to contain them. */
export const DENY = new Set(['band', 'bands', 'legacy', 'template', 'templates', 'generator', 'generators', 'pane', 'panes', 'kit',
    'opts', 'variant', 'variants', 'proposal', 'proposals', 'lane', 'lanes', 'tagged', 'tagging', 'tagfix', 'registry',
    'dispatcher', 'dispatch', 'cell', 'andika', 'deals', 'dealt', 'reception', 'spec', 'specs', 'json', 'js', 'md', 'csv',
    'id', 'ids', 'path', 'repo', 'regrade', 'grader', 'sampled', 'resampled', 'audit', 'audited', 'verdict', 'verdicts', 'mc', 'wrm',
    'deal', 'dealing', 'gr', 'yr', 'pk', 'rec', 'wk', 'descartes', 'nwea', 'payload', 'render', 'renders', 'rendered', 'host', 'hosts', 'svg', 'html',
    'enum', 'bool', 'config', 'param', 'params', 'stub', 'tombstone', 'alias', 'aliases', 'routes', 'routed', 'schema', 'lint', 'critic',
    'rubric', 'fallback', 'migrate', 'migrated', 'migration', 'facsimile', 'provider', 'providers', 'footprint', 'seed', 'seeded']);
/** Upper-case words a teacher reads on these screens: MAP and its RIT scale, the standards (CCSS, EE) and the
 *  CCSS domain letters the school's units are named by. */
export const ACRONYMS = new Set(['MAP', 'RIT', 'CCSS', 'EE', 'K', 'US', 'AM', 'PM', 'I', 'CC', 'OA', 'NBT', 'NF', 'MD', 'G', 'E',
    'RP', 'NS', 'SP', 'GCF', 'LCM', 'ALL', 'CSV', 'LCD', 'IQR', 'MAD', 'FDP']);
/** Single letters: "a", "I", the times sign x, and N / M / n as "a number" ("share N among M"). Any other single
 *  letter passes only in a maths context, next to an operator or in a list ("a/b = a ÷ b", "(g, kg, mL, L)"). */
const SINGLE = new Set(['a', 'A', 'I', 'x', 'N', 'M', 'n']);
const MATH_NEXT = /[×÷=+−\-/,:→←<>·*√%°]/;
/** Measures written as their units ("mL", "kg") pass as words. */
const UNIT_WORDS = new Set(['cm', 'mm', 'km', 'kg', 'mL', 'ml', 'ft', 'yd', 'oz', 'lb', 'lbs', 'min', 'mins', 'hr', 'hrs', 'sec', 'mph']);
// code characters: braces, brackets, backticks, pipes, backslashes; an underscore only inside a word (snake_case)
// — a run of underscores alone is a blank to fill ("7 + 5 = __ + 3")
const CODE_CHARS = /[{}[\]`|\\~^]|[A-Za-z0-9]_|_[A-Za-z0-9]/;
const STD_CODE = /\b(?:M\.)?(?:EE\.)?[K1-8]\.[A-Z]{1,3}(?:\.[A-Z])?(?:\.\d{1,2}[a-z]?)?(?:\.[A-Za-z])?\b/g;
const ABBR = /\b(?:e\.g|i\.e|a\.m|p\.m|incl|approx)\.?(?![A-Za-z])/g;
const UNITS = 'cm|mm|km|kg|mL|ml|L|g|m|ft|yd|oz|lbs?|min|mins|hr|hrs|mi|p|c';

/** The tokens of a line: runs of letters and digits ("week", "12", "2s", "D1", "S13"); standard codes and
 *  e.g. / i.e. are taken out first, and 1,000 / 2.5 count as one number. */
function tokensAt(text) {
    // "RIT band" is MAP's own word for a score range (the option word "band" alone stays out)
    const s = String(text || '').replace(/\bRIT bands?\b/g, (m) => `RIT${' '.repeat(m.length - 3)}`).replace(ABBR, (m) => ' '.repeat(m.length)).replace(/\b([23])-D\b/g, '$1D ').replace(STD_CODE, (m) => ' '.repeat(m.length))
        .replace(/\d+(?:[.,]\d+)+/g, (m) => '0'.repeat(m.length));
    return [...s.matchAll(/[A-Za-z0-9]+(?:['’][A-Za-z]+)?/g)].map((m) => ({ tok: m[0], i: m.index, s }));
}
export function wordTokens(text) { return tokensAt(text).map((x) => x.tok); }
/** Is the token at i written as maths (an operator or list mark right before or after it)? */
function inMaths(s, i, len) {
    const before = s.slice(0, i).replace(/\s+$/, '').slice(-1);
    const after = s.slice(i + len).replace(/^\s+/, '').charAt(0);
    if (before === '&' || after === '&') return false;   // "B&W" is never maths
    return MATH_NEXT.test(before || ' ') || MATH_NEXT.test(after || ' ');
}

/** Why a token is not plain, or '' when it is. */
export function tokenProblem(tok) {
    const t = String(tok).replace(/['’]s$/i, '');
    if (/^\d+$/.test(t)) return '';                                       // a number
    if (/^\d+(?:st|nd|rd|th|ths|s|x)$/.test(t)) return '';                // 3rd, 2s, 100s, 25ths, 10x
    if (new RegExp(`^\\d+(?:${UNITS})$`).test(t)) return '';             // 5cm, 20p
    if (/^[23]D$/.test(t)) return '';                                       // 2D, 3D
    if (/^D\d$|^(?:CC|OA|MD|NBT|NF|G)\d{1,2}$/.test(t)) return '';        // the school's units: D1, CC3, MD1
    if (/\d/.test(t)) return 'code (letters and digits)';                 // S13, W05, Y3, B2
    if (SINGLE.has(t) || ACRONYMS.has(t) || UNIT_WORDS.has(t)) return '';
    if (t.length === 1) return 'single letter';
    if (/[A-Z]/.test(t.slice(1))) return ACRONYMS.has(t) ? '' : (t === t.toUpperCase() ? 'acronym' : 'mixed case');
    const w = t.toLowerCase().replace(/['’]/g, '');
    if (DENY.has(w)) return 'build word';
    if (WORDS.has(w)) return '';
    return 'not a plain word';
}

/**
 * The first reason a line is not plain English, as { why, at } — or null when it is plain.
 * opts.fragment (default true): the line must start like a sentence (a capital, a digit or a quote). The
 * screen-wide sweep turns it off for chrome lines ("and 3 more", "· Covers part").
 */
export function plainProblem(text, opts = {}) {
    const s = String(text == null ? '' : text).trim();
    if (!s) return null;
    if (CODE_CHARS.test(s)) return { why: 'code character', at: s.match(CODE_CHARS)[0] };
    if (/undefined|NaN|\[object/.test(s)) return { why: 'broken', at: s };
    if (opts.fragment !== false && !/^["“‘(£$0-9A-Z−-]|^(?:a\.m\.|p\.m\.)/.test(s)) return { why: 'fragment (starts lower case or with punctuation)', at: s.slice(0, 12) };
    if (opts.fragment !== false && /^\d+\.\d+\s+[a-z]/.test(s)) return { why: 'starts with a section number', at: s.slice(0, 12) };
    let depth = 0;
    for (const ch of s) {
        if (ch === '(') depth += 1;
        if (ch === ')') { depth -= 1; if (depth < 0) return { why: 'closes a bracket it never opened', at: s.slice(0, 40) }; }
    }
    if (depth) return { why: 'unbalanced bracket', at: s.slice(0, 40) };
    if ((s.match(/"/g) || []).length % 2) return { why: 'unbalanced quote', at: s.slice(0, 40) };
    if ((s.match(/“/g) || []).length !== (s.match(/”/g) || []).length) return { why: 'unbalanced quote', at: s.slice(0, 40) };
    const dang = /\(\s|\s\)|\(\s*\)|\s[,;:.](?=\s|$)|\(\s*[,;:]|\)-"|[,;:]\s*[,;:.]/.exec(s);
    if (dang) return { why: 'dangling punctuation', at: dang[0] };
    const dbl = /\b([A-Za-z]+)\s+\1\b/i.exec(s);
    if (dbl) return { why: 'doubled word', at: dbl[0] };
    for (const { tok, i, s: masked } of tokensAt(s)) {
        const p = tokenProblem(tok);
        if (p && !(p === 'single letter' && inMaths(masked, i, tok.length))) return { why: p, at: tok };
    }
    return null;
}

/** True when the whole line may be shown to a teacher as it is. */
export const isPlain = (text, opts) => !plainProblem(text, opts);

/** The note, whole (first letter capitalised, a final full stop), when it is plain — else ''. Never a part of it. */
export function plainNote(text) {
    const s = String(text == null ? '' : text).replace(/\s+/g, ' ').trim().replace(/[;,:]$/, '');
    if (!s) return '';
    const cap = s.charAt(0).toUpperCase() + s.slice(1);
    const out = /[.!?)"”]$/.test(cap) ? cap : `${cap}.`;
    return isPlain(out) ? out : '';
}
