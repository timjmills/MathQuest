// visual-catalogue.js — the ONE de-duplicated catalogue of White Rose representations (the pictures,
// models and layouts WRM draws on its lesson pages), folded from the seven year catalogues
// design/wrm-visuals/{reception,year-1 … year-6}.md. Owner, 2026-09-25: every WRM visual is to be
// replicated in our skills, as an option within a skill or as a skill of its own.
//
// A pure data module, NOT imported by the app. `node tests/scripts/ws-standards.cjs --report` reads the
// year tables, groups their rows by this file, and writes design/wrm-visuals/INDEX.md (the catalogue)
// and the "added from visual catalogue" entries of design/BUILD_LIST.md.
//
// HOW THE ROWS BECOME ONE CATALOGUE
//   * Every row of a year's "Every … representation (de-duplicated)" table is keyed `<year>:<id>`
//     (R:R04 = Reception R04, Y5:N5-03, Y6:Y2:R87 …).
//   * The years' own cross-references join rows automatically: Years 2, 5 and 6 reuse the Year 3 ids
//     (R01–R84) and the Year 2 additions (R85–R101); Year 1 and Year 4 name the Year 3 / Year 1 row in
//     their cross-reference columns.
//   * VISUAL_ALIASES joins the rest by hand (Reception has no cross-reference column, and the "NEW"
//     rows of Years 4–6 repeat each other: the Gattegno chart is Y4 R06 = Y5 N5-04 = Y6 N02). A value
//     of null cuts a wrong automatic join (Y1 R18's cross-reference names a Year 3 STEP, not a row).
//   * VISUALS pins the final id of each group to one of its rows (the anchor), a short name, and the
//     build-list entries that close it: an entry id from build-list.js (a WRM or standards proposal
//     that already draws it — merged, never duplicated) or a `vis_*` entry of VISUAL_BUILDS.
//   * Status is computed from the year rows: MATCH when every year row is MATCH, GAP when every year
//     row is GAP, PARTIAL otherwise. A MATCH needs no entry; PARTIAL and GAP need at least one.

